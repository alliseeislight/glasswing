	hl.exec_cmd(home .. "/.local/bin/glass-files --gapplication-service")
	hl.exec_cmd(home .. "/.local/bin/bar-start")
	hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
	hl.exec_cmd(home .. "/.config/hypr/scripts/cycle_wall.sh")
