# ---------------- Lua scanning (binds / autostart) ----------------
def call_end(text, start):
    i = text.index("(", start)
    depth, n = 0, len(text)
    while i < n:
        if text.startswith("--", i):
            j = text.find("\n", i)
            if j < 0:
                return -1
            i = j
            continue
        c = text[i]
        if c in "\"'":
            q = c
            i += 1
            while i < n and text[i] != q:
                if text[i] == "\\":
                    i += 1
                i += 1
        elif text.startswith("[[", i):
            j = text.find("]]", i)
            if j < 0:
                return -1
            i = j + 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def split_args(inner):
    args, cur, depth, i, n = [], [], 0, 0, len(inner)
    while i < n:
        c = inner[i]
        if c in "\"'":
            q = c
            cur.append(c)
            i += 1
            while i < n and inner[i] != q:
                if inner[i] == "\\":
                    cur.append(inner[i])
                    i += 1
                cur.append(inner[i])
                i += 1
            cur.append(q)
        elif inner.startswith("[[", i):
            j = inner.find("]]", i)
            j = n - 2 if j < 0 else j
            cur.append(inner[i:j + 2])
            i = j + 1
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail:
        args.append(tail)
    return args


def pretty_keys(expr):
    out = []
    for p in (x.strip() for x in expr.split("..")):
        if p == "M":
            out.append("SUPER")
        elif p[:1] in "\"'" and len(p) >= 2:
            out.append(p[1:-1])
        elif p:
            out.append("<" + p + ">")
    return re.sub(r"\s+", " ", "".join(out)).strip()


def _tidy(s):
    s = " ".join(s.split())
    s = s.replace('os.getenv("HOME") .. "', '"~').replace("hl.dsp.", "")
    return s


def pretty_action(arg):
    a = _tidy(arg)
    if a.startswith("exec_cmd(") and a.endswith(")"):
        inner = a[len("exec_cmd("):-1].strip()
        if inner.startswith("[["):
            inner = inner[2:]
            inner = inner[:-2] if inner.endswith("]]") else inner
        elif inner.startswith('"') and inner.endswith('"') and len(inner) >= 2:
            inner = inner[1:-1]
        a = "run: " + inner.strip()
        pm = re.search(r"popup\.sh (\w+)", a)
        if pm:
            a = "open the " + pm.group(1) + " popup" if pm.group(1) != "daemon" else "start the popup daemon"
    elif a.startswith("function"):
        a = "script: " + a.removeprefix("function()").removesuffix("end").strip()
    return a if len(a) <= 84 else a[:83] + "…"


def parse_binds(text):
    res = []
    for m in re.finditer(r"hl\.bind\(", text):
        ls = text.rfind("\n", 0, m.start()) + 1
        if text[ls:m.start()].lstrip().startswith("--"):
            continue
        e = call_end(text, m.start())
        if e < 0:
            continue
        args = split_args(text[m.end():e - 1])
        if len(args) >= 2:
            res.append((pretty_keys(args[0]), pretty_action(args[1])))
    return res


_AUTO = re.compile(r"^(\s*)(--\s*)?(hl\.exec_cmd\((.*)\))\s*$")


def parse_autostart(text):
    res = []
    for idx, line in enumerate(text.split("\n")):
        m = _AUTO.match(line)
        if not m:
            continue
        inner = m.group(4).strip()
        pretty = _tidy(inner).strip('"').strip()
        protected = "popup.sh daemon" in inner or "glassd" in inner
        res.append({"idx": idx, "enabled": m.group(2) is None, "text": pretty, "protected": protected})
    return res


def set_autostart(text, idx, enabled):
    lines = text.split("\n")
    m = _AUTO.match(lines[idx])
    if not m:
        return text
    lines[idx] = m.group(1) + ("" if enabled else "-- ") + m.group(3)
    return "\n".join(lines)


# ---------------- lock screen ----------------
_LOCK_BLOCK = re.compile(r"(?ms)^([ \t]*)([A-Za-z][\w-]*)\s*\{\s*\n(.*?)^\1\}")


def _lock_blocks(text, header):
    return [m for m in _LOCK_BLOCK.finditer(text) if m.group(2) == header]


def _lock_fields(text, header, index=0):
    blocks = _lock_blocks(text, header)
    if index >= len(blocks):
        return {}
    fields = {}
    for line in blocks[index].group(3).splitlines():
        m = re.match(r"^\s*([A-Za-z][\w-]*)\s*=\s*(.*?)\s*$", line)
        if m:
            fields[m.group(1)] = m.group(2)
    return fields


def _lock_patch(text, header, index, values):
    """Change fields in one existing Hyprlock widget without rewriting the file."""
    blocks = _lock_blocks(text, header)
    if index >= len(blocks):
        return text
    block = blocks[index]
    lines = block.group(3).rstrip("\n").splitlines()
    for key, value in values.items():
        pat = re.compile(r"^(\s*)" + re.escape(key) + r"\s*=")
        for i, line in enumerate(lines):
            m = pat.match(line)
            if m:
                lines[i] = f"{m.group(1)}{key} = {value}"
                break
        else:
            lines.append(f"    {key} = {value}")
    inner = "\n".join(lines) + "\n"
    return text[:block.start(3)] + inner + text[block.end(3):]


def _lock_int(value, default):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return default


def _lock_float(value, default):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _lock_size(value, default):
    m = re.match(r"\s*(\d+)\s*,\s*(\d+)", value or "")
    return (int(m.group(1)), int(m.group(2))) if m else default


def _lock_opacity(value, default):
    m = re.search(r"rgba\(\s*[^,]+,\s*[^,]+,\s*[^,]+,\s*([0-9.]+)\s*\)", value or "")
    return float(m.group(1)) if m else default


def read_lock_config():
    """Seed the settings page from the current (possibly hand-edited) config."""
    text = read(LOCK_CONF)
    st = dict(LOCK_DEFAULTS)
    bg = _lock_fields(text, "background")
    shape = _lock_fields(text, "shape")
    inp = _lock_fields(text, "input-field")

    path = os.path.expanduser(bg.get("path", "screenshot").strip())
    st["wallpaper"] = path or "screenshot"
    st["blur_size"] = _lock_int(bg.get("blur_size"), st["blur_size"])
    st["blur_passes"] = _lock_int(bg.get("blur_passes"), st["blur_passes"])
    st["brightness"] = _lock_float(bg.get("brightness"), st["brightness"])
    st["vibrancy"] = _lock_float(bg.get("vibrancy"), st["vibrancy"])
    st["noise"] = _lock_float(bg.get("noise"), st["noise"])

    w, h = _lock_size(shape.get("size"), (st["card_width"], st["card_height"]))
    st["card_width"], st["card_height"] = w, h
    st["card_opacity"] = _lock_opacity(shape.get("color"), st["card_opacity"])
    st["card_rounding"] = _lock_int(shape.get("rounding"), st["card_rounding"])
    st["card_border"] = _lock_int(shape.get("border_size"), st["card_border"])

    labels = [_lock_fields(text, "label", i) for i in range(3)]
    clock = labels[0].get("text", "$TIME")
    st["clock_24h"] = "%I" not in clock and "%-I" not in clock
    st["clock_seconds"] = "%S" in clock
    st["clock_size"] = _lock_int(labels[0].get("font_size"), st["clock_size"])
    date = labels[1].get("text", "")
    st["show_date"] = bool(date.strip())
    m = re.search(r'date\s+\+"([^"]*)"', date)
    if m:
        st["date_format"] = m.group(1)
    st["date_size"] = _lock_int(labels[1].get("font_size"), st["date_size"])
    st["show_user"] = bool(labels[2].get("text", "").strip())

    iw, ih = _lock_size(inp.get("size"), (st["input_width"], st["input_height"]))
    st["input_width"], st["input_height"] = iw, ih
    st["input_rounding"] = _lock_int(inp.get("rounding"), st["input_rounding"])
    ph = re.sub(r"<[^>]+>", "", inp.get("placeholder_text", "")).strip()
    if ph:
        st["placeholder"] = html.unescape(ph)
    return st


def load_lock_settings():
    if not os.path.isfile(LOCK_SETTINGS):
        st = read_lock_config()
        save_lock_settings(st)
        return st
    try:
        data = json.loads(read(LOCK_SETTINGS, "{}"))
    except ValueError:
        data = {}
    if not isinstance(data, dict):
        data = {}
    st = dict(LOCK_DEFAULTS)
    for key, default in LOCK_DEFAULTS.items():
        if key not in data:
            continue
        value = data[key]
        if isinstance(default, bool):
            st[key] = value if isinstance(value, bool) else default
        elif isinstance(default, int):
            st[key] = _lock_int(value, default)
        elif isinstance(default, float):
            st[key] = _lock_float(value, default)
        elif isinstance(value, str):
            st[key] = value
    return st


def save_lock_settings(st):
    out = dict(LOCK_DEFAULTS)
    for key in LOCK_DEFAULTS:
        if key in st:
            out[key] = st[key]
    write_atomic(LOCK_SETTINGS, json.dumps(out, indent=2) + "\n")
    return out


def _lock_clock_text(st):
    fmt = "%H:%M" if st["clock_24h"] else "%-I:%M"
    if st["clock_seconds"]:
        fmt += ":%S"
    if not st["clock_24h"]:
        fmt += " %p"
    return f'cmd[update:1000] date +"{fmt}"'


def _lock_date_text(st):
    if not st["show_date"]:
        return " "
    return f'cmd[update:60000] date +"{st["date_format"]}"'


def _lock_placeholder(st):
    text = html.escape(str(st.get("placeholder", "")), quote=False)
    return f'<span foreground="##ffffff99">{text}</span>' if text else '<span foreground="##ffffff99"></span>'


def apply_lock_settings(st=None):
    """Write the managed values into ~/.config/hypr/hyprlock.conf."""
    st = save_lock_settings(st or load_lock_settings())
    text = read(LOCK_CONF)
    if not text:
        raise ValueError("hyprlock.conf was not found")

    wallpaper = os.path.expanduser(str(st["wallpaper"]))
    if wallpaper != "screenshot" and not os.path.isfile(wallpaper):
        raise ValueError("The selected lock screen wallpaper no longer exists")

    text = _lock_patch(text, "background", 0, {
        "path": wallpaper,
        "blur_size": int(st["blur_size"]),
        "blur_passes": int(st["blur_passes"]),
        "brightness": f'{float(st["brightness"]):.2f}',
        "vibrancy": f'{float(st["vibrancy"]):.2f}',
        "noise": f'{float(st["noise"]):.3f}',
    })
    text = _lock_patch(text, "shape", 0, {
        "size": f'{int(st["card_width"])}, {int(st["card_height"])}',
        "color": f'rgba(20, 22, 32, {float(st["card_opacity"]):.2f})',
        "rounding": int(st["card_rounding"]),
        "border_size": int(st["card_border"]),
    })
    text = _lock_patch(text, "label", 0, {
        "text": _lock_clock_text(st),
        "font_size": int(st["clock_size"]),
    })
    text = _lock_patch(text, "label", 1, {
        "text": _lock_date_text(st),
        "font_size": int(st["date_size"]),
    })
    text = _lock_patch(text, "label", 2, {
        "text": "$USER" if st["show_user"] else " ",
    })
    text = _lock_patch(text, "input-field", 0, {
        "size": f'{int(st["input_width"])}, {int(st["input_height"])}',
        "rounding": int(st["input_rounding"]),
        "placeholder_text": _lock_placeholder(st),
    })

    backup_once(LOCK_CONF)
    write_atomic(LOCK_CONF, text)
    return True


# ---------------- SDDM login screen ----------------
def _sddm_conf_files():
    files = [SDDM_CONF]
    try:
        files.extend(sorted(glob.glob(os.path.join(SDDM_CONF_DIR, "*.conf"))))
    except OSError:
        pass
    return [p for p in files if os.path.isfile(p)]


def _sddm_main_config():
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    try:
        parser.read(_sddm_conf_files())
    except (configparser.Error, OSError):
        return parser
    return parser


def _sddm_values(path):
    parser = configparser.RawConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    try:
        parser.read(path)
    except (configparser.Error, OSError):
        return {}
    if parser.has_section("General"):
        return dict(parser.items("General"))
    values = {}
    for section in parser.sections():
        values.update(dict(parser.items(section)))
    return values


def _sddm_lookup(values, *names, default=""):
    lower = {k.lower(): v for k, v in values.items()}
    for name in names:
        value = lower.get(name.lower())
        if value is not None:
            return value
    return default


def _sddm_actual_key(values, *names):
    lower = {k.lower(): k for k in values}
    for name in names:
        key = lower.get(name.lower())
        if key:
            return key
    return ""


def _sddm_unquote(value):
    value = (value or "").strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def _sddm_kind(path):
    return "video" if str(path).lower().endswith(VID) else "image"


def _sddm_qml_string(text, prop):
    m = re.search(r'property\s+string\s+' + re.escape(prop) + r'\s*:\s*"([^"]+)"', text)
    return os.path.expanduser(m.group(1)) if m else ""


def sddm_theme_info():
    cfg = _sddm_main_config()
    try:
        name = _sddm_unquote(cfg.get("Theme", "Current", fallback=""))
    except (configparser.Error, ValueError):
        name = ""
    configured = ""
    try:
        configured = _sddm_unquote(cfg.get("Theme", "ThemeDir", fallback=""))
    except (configparser.Error, ValueError):
        pass

    dirs = [configured, SDDM_THEMES, SDDM_THEMES_LOCAL]
    theme_dir = ""
    if name:
        for base in dirs:
            if not base:
                continue
            candidate = os.path.join(base, name)
            if os.path.isdir(candidate):
                theme_dir = candidate
                break

    main = read(os.path.join(theme_dir, "Main.qml")) if theme_dir else ""
    return {
        "name": name,
        "dir": theme_dir,
        "conf": os.path.join(theme_dir, "theme.conf") if theme_dir else "",
        "main": main,
        "cache": _sddm_qml_string(main, "cachePath"),
        "kind": _sddm_qml_string(main, "cacheKindPath"),
    }


def _sddm_default_path(info, values):
    candidates = []
    if info["dir"]:
        candidates.extend([
            os.path.join(info["dir"], "assets", "background.jpg"),
            os.path.join(info["dir"], "background.jpg"),
        ])
    bg = _sddm_unquote(_sddm_lookup(values, "background", "Background"))
    if bg:
        candidates.append(bg if os.path.isabs(bg) else os.path.join(info["dir"], bg))
    for path in candidates:
        if path and os.path.isfile(path):
            return path
    return ""


def read_sddm_settings():
    info = sddm_theme_info()
    values = _sddm_values(info["conf"]) if info["conf"] else {}
    out = dict(info)
    out.update({
        "theme": info["name"],
        "theme_dir": info["dir"],
        "theme_conf": info["conf"],
        "blur_key": _sddm_actual_key(values, "backgroundBlur"),
        "dim_key": _sddm_actual_key(values, "backgroundDim"),
        "clock_key": _sddm_actual_key(values, "clockFormat"),
        "date_key": _sddm_actual_key(values, "dateFormat"),
        "blur": 48,
        "dim": 0.12,
        "clock_format": "h:mm",
        "date_format": "ddd MMM d",
        "clock_24h": False,
        "clock_seconds": False,
        "default_wallpaper": _sddm_default_path(info, values),
        "wallpaper": "",
        "wallpaper_kind": "image",
    })
    if out["blur_key"]:
        out["blur"] = _lock_int(_sddm_lookup(values, out["blur_key"]), 48)
    if out["dim_key"]:
        out["dim"] = _lock_float(_sddm_lookup(values, out["dim_key"]), 0.12)
    if out["clock_key"]:
        out["clock_format"] = _sddm_unquote(_sddm_lookup(values, out["clock_key"])) or "h:mm"
        out["clock_24h"] = "H" in out["clock_format"]
        out["clock_seconds"] = "s" in out["clock_format"]
    if out["date_key"]:
        out["date_format"] = _sddm_unquote(_sddm_lookup(values, out["date_key"]))

    cache = info["cache"]
    if cache and os.path.isfile(cache):
        out["wallpaper"] = cache
        kind = read(info["kind"], "").strip().lower()
        out["wallpaper_kind"] = kind if kind in ("image", "video") else _sddm_kind(cache)
    else:
        fallback = _sddm_default_path(info, values)
        out["wallpaper"] = fallback
        out["wallpaper_kind"] = _sddm_kind(fallback)
    return out


def _sddm_patch(text, key, value):
    value = str(value).replace("\n", " ").replace("\r", " ")
    pattern = re.compile(r"(?m)^([ \t]*)" + re.escape(key) + r"\s*=(.*)$", re.I)
    match = pattern.search(text)
    if match:
        raw = match.group(2).strip()
        quote = raw[0] if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'" else ""
        return text[:match.start()] + f"{match.group(1)}{key}={quote}{value}{quote}" + text[match.end():]

    general = re.search(r"(?m)^\[General\][ \t]*\r?$", text)
    if general:
        start = general.end()
        next_section = re.search(r"(?m)^\[[^\]]+\][ \t]*\r?$", text[start:])
        end = start + next_section.start() if next_section else len(text)
        block = text[start:end]
        if block and not block.endswith("\n"):
            block += "\n"
        return text[:start] + block + f"{key}={value}\n" + text[end:]
    return text.rstrip("\n") + f"\n[General]\n{key}={value}\n"


def set_sddm_values(updates):
    info = sddm_theme_info()
    conf = info["conf"]
    if not conf or not os.path.isfile(conf):
        raise ValueError("This SDDM theme has no editable theme.conf")
    text = read(conf)
    for key, value in updates.items():
        text = _sddm_patch(text, key, value)
    backup_once(conf)
    write_atomic(conf, text)
    return True


def _sddm_copy_public(src, dst):
    if os.path.realpath(src) == os.path.realpath(dst):
        os.chmod(dst, 0o644)
        return
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    tmp = dst + f".tmp-{os.getpid()}"
    shutil.copyfile(src, tmp)
    os.chmod(tmp, 0o644)
    os.replace(tmp, dst)


def set_sddm_wallpaper(src):
    src = os.path.expanduser(str(src))
    if not os.path.isfile(src):
        raise ValueError("That login wallpaper no longer exists")
    info = sddm_theme_info()
    if not info["name"]:
        raise ValueError("No SDDM theme was detected")

    kind = _sddm_kind(src)
    cache = info["cache"]
    if cache:
        try:
            _sddm_copy_public(src, cache)
            kind_path = info["kind"] or cache + ".kind"
            write_atomic(kind_path, kind + "\n")
            os.chmod(kind_path, 0o644)
            return cache
        except OSError:
            if os.path.exists(cache):
                raise

    if not info["dir"]:
        raise ValueError("No SDDM theme directory was found")
    values = _sddm_values(info["conf"])
    target_dir = os.path.join(info["dir"], "assets")
    if not os.path.isdir(target_dir):
        target_dir = os.path.join(info["dir"], "backgrounds")
    if not os.path.isdir(target_dir):
        target_dir = info["dir"]
    ext = os.path.splitext(src)[1].lower() or (".mp4" if kind == "video" else ".jpg")
    target = os.path.join(target_dir, "login-wallpaper" + ext)
    _sddm_copy_public(src, target)

    key = _sddm_actual_key(values, "Background", "background")
    if not key:
        key = "Background" if re.search(r"config\.Background", info["main"]) else "background"
    set_sddm_values({key: os.path.relpath(target, info["dir"])})
    return target


def set_sddm_default_wallpaper():
    info = sddm_theme_info()
    values = _sddm_values(info["conf"]) if info["conf"] else {}
    path = _sddm_default_path(info, values)
