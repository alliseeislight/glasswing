# ---------------- Hyprland overrides (Lua) ----------------
def lua_tree(overrides):
    tree = {}
    for key, val in overrides.items():
        parts = key.split(":")
        cur = tree
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = val
    return tree


def _lua_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    return '"' + str(v).replace('"', '\\"') + '"'


def lua_dump(tree, ind=2):
    pad = "\t" * ind
    lines = []
    for k, v in tree.items():
        if isinstance(v, dict):
            lines.append(f"{pad}{k} = {{")
            lines.append(lua_dump(v, ind + 1))
            lines.append(f"{pad}}},")
        else:
            lines.append(f"{pad}{k} = {_lua_val(v)},")
    return "\n".join(lines)


def lua_text(overrides):
    if not overrides:
        return "-- generated by glass settings (no overrides)\n"
    tree = lua_tree(overrides)
    top = []
    for k, v in tree.items():
        top.append(f"\t{k} = {{")
        top.append(lua_dump(v, 2))
        top.append("\t},")
    return "-- generated by glass settings; change these in the Settings app\nhl.config({\n" + "\n".join(top) + "\n})\n"


