def read(path, default=""):
    try:
        with open(path) as f:
            return f.read()
    except OSError:
        return default


def write_atomic(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def backup_once(path):
    """One backup per session of any file we are about to rewrite."""
    bak = f"{path}.pre-settings-{_STAMP}"
    if os.path.exists(path) and not os.path.exists(bak):
        try:
            shutil.copy(path, bak)
        except OSError:
            pass


# ---------------- settings.json ----------------
def load_settings():
    try:
        d = json.loads(read(SETTINGS, "{}"))
        return d if isinstance(d, dict) else {}
    except ValueError:
        return {}


def save_settings(d):
    write_atomic(SETTINGS, json.dumps(d, indent=2) + "\n")


# ---------------- Hyprland overrides (Lua) ----------------
def lua_tree(overrides):
    tree = {}
    for key, val in overrides.items():
        parts = key.split(":")
        cur = tree
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
        cur[parts[-1]] = val
    return tree


def _lua_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    return '"' + str(v).replace('"', '\\"') + '"'


def lua_dump(tree, ind=2):
    pad = "\t" * ind
    lines = []
    for k, v in tree.items():
        if isinstance(v, dict):
            lines.append(f"{pad}{k} = {{")
            lines.append(lua_dump(v, ind + 1))
            lines.append(f"{pad}}},")
        else:
            lines.append(f"{pad}{k} = {_lua_val(v)},")
    return "\n".join(lines)


def lua_text(overrides):
    if not overrides:
        return "-- generated by glass settings (no overrides)\n"
    tree = lua_tree(overrides)
    top = []
    for k, v in tree.items():
        top.append(f"\t{k} = {{")
        top.append(lua_dump(v, 2))
        top.append("\t},")
    return "-- generated by glass settings; change these in the Settings app\nhl.config({\n" + "\n".join(top) + "\n})\n"


# ---------------- wallpapers & palette ----------------
def wallpapers():
    out = []
    for p in sorted(glob.glob(os.path.join(WALLS, "*"))):
        low = p.lower()
        if low.endswith(IMG):
            out.append((p, False))
        elif low.endswith(VID):
            out.append((p, True))
    return out


def current_wallpaper():
    m = re.search(r"^\s*wallpaper\s*=\s*(.+?)\s*$", read(WAYPAPER_INI), re.M)
    return os.path.expanduser(m.group(1)) if m else ""


def palette_get():
    m = re.search(r'^\s*palette\s*=\s*"([^"]+)"', read(WALLUST_TOML), re.M)
    return m.group(1) if m else ""


def palette_set(name):
    text = read(WALLUST_TOML)
    if not re.search(r'^\s*palette\s*=', text, re.M):
        return False
    backup_once(WALLUST_TOML)
    write_atomic(WALLUST_TOML, re.sub(r'^(\s*palette\s*=\s*)"[^"]*"', rf'\1"{name}"', text, count=1, flags=re.M))
    return True


# ---------------- Lua scanning (binds / autostart) ----------------
def call_end(text, start):
    i = text.index("(", start)
    depth, n = 0, len(text)
    while i < n:
        if text.startswith("--", i):
            j = text.find("\n", i)
            if j < 0:
                return -1
            i = j
            continue
        c = text[i]
        if c in "\"'":
            q = c
            i += 1
            while i < n and text[i] != q:
                if text[i] == "\\":
                    i += 1
                i += 1
        elif text.startswith("[[", i):
            j = text.find("]]", i)
            if j < 0:
                return -1
            i = j + 1
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def split_args(inner):
    args, cur, depth, i, n = [], [], 0, 0, len(inner)
    while i < n:
        c = inner[i]
        if c in "\"'":
            q = c
            cur.append(c)
            i += 1
            while i < n and inner[i] != q:
                if inner[i] == "\\":
                    cur.append(inner[i])
                    i += 1
                cur.append(inner[i])
                i += 1
            cur.append(q)
        elif inner.startswith("[[", i):
            j = inner.find("]]", i)
            j = n - 2 if j < 0 else j
            cur.append(inner[i:j + 2])
            i = j + 1
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail:
        args.append(tail)
    return args


def pretty_keys(expr):
    out = []
    for p in (x.strip() for x in expr.split("..")):
        if p == "M":
            out.append("SUPER")
        elif p[:1] in "\"'" and len(p) >= 2:
            out.append(p[1:-1])
        elif p:
            out.append("<" + p + ">")
    return re.sub(r"\s+", " ", "".join(out)).strip()


def _tidy(s):
    s = " ".join(s.split())
    s = s.replace('os.getenv("HOME") .. "', '"~').replace("hl.dsp.", "")
    return s


def pretty_action(arg):
    a = _tidy(arg)
    if a.startswith("exec_cmd(") and a.endswith(")"):
        inner = a[len("exec_cmd("):-1].strip()
        if inner.startswith("[["):
            inner = inner[2:]
            inner = inner[:-2] if inner.endswith("]]") else inner
        elif inner.startswith('"') and inner.endswith('"') and len(inner) >= 2:
            inner = inner[1:-1]
        a = "run: " + inner.strip()
        pm = re.search(r"popup\.sh (\w+)", a)
        if pm:
            a = "open the " + pm.group(1) + " popup" if pm.group(1) != "daemon" else "start the popup daemon"
    elif a.startswith("function"):
        a = "script: " + a.removeprefix("function()").removesuffix("end").strip()
    return a if len(a) <= 84 else a[:83] + "…"


def parse_binds(text):
    res = []
    for m in re.finditer(r"hl\.bind\(", text):
        ls = text.rfind("\n", 0, m.start()) + 1
        if text[ls:m.start()].lstrip().startswith("--"):
            continue
        e = call_end(text, m.start())
        if e < 0:
            continue
        args = split_args(text[m.end():e - 1])
        if len(args) >= 2:
            res.append((pretty_keys(args[0]), pretty_action(args[1])))
    return res


_AUTO = re.compile(r"^(\s*)(--\s*)?(hl\.exec_cmd\((.*)\))\s*$")


def parse_autostart(text):
    res = []
    for idx, line in enumerate(text.split("\n")):
        m = _AUTO.match(line)
        if not m:
            continue
        inner = m.group(4).strip()
        pretty = _tidy(inner).strip('"').strip()
        protected = "popup.sh daemon" in inner or "glassd" in inner
        res.append({"idx": idx, "enabled": m.group(2) is None, "text": pretty, "protected": protected})
    return res


def set_autostart(text, idx, enabled):
    lines = text.split("\n")
    m = _AUTO.match(lines[idx])
    if not m:
        return text
    lines[idx] = m.group(1) + ("" if enabled else "-- ") + m.group(3)
    return "\n".join(lines)


