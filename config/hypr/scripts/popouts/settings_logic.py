def monitors_summary(data):
    out = []
    for m in data if isinstance(data, list) else []:
        try:
            out.append(f"{m['name']}  {m['width']}x{m['height']}@{round(m['refreshRate'])}Hz  scale {m['scale']:g}")
        except (KeyError, TypeError, ValueError):
            continue
    return out
